"""Generates source/font8x16.h (ASCII 32-126, 8x16, 1bpp) from DejaVu Sans Mono Bold."""
from PIL import Image, ImageDraw, ImageFont
import sys
path = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"
font = ImageFont.truetype(path, 13)
rows = []
sheet = Image.new("L", (8 * 95, 16), 0)
for i, code in enumerate(range(32, 127)):
    img = Image.new("L", (8, 16), 0)
    d = ImageDraw.Draw(img)
    d.text((0, 0), chr(code), font=font, fill=255)
    sheet.paste(img, (i * 8, 0))
    bytes_ = []
    for y in range(16):
        b = 0
        for x in range(8):
            if img.getpixel((x, y)) > 100:
                b |= 0x80 >> x
        bytes_.append(b)
    rows.append(bytes_)
with open("source/font8x16.h", "w") as f:
    f.write("/* Generated by tools/genfont.py from DejaVu Sans Mono Bold (free license). ASCII 32-126, 8x16, MSB = left pixel. */\n")
    f.write("#pragma once\nstatic const unsigned char font8x16[95][16] = {\n")
    for code, r in zip(range(32, 127), rows):
        ch = chr(code).replace("\\", "\\\\").replace("*/", "* /")
        f.write("    {" + ",".join("0x%02x" % b for b in r) + "}, /* " + ch + " */\n")
    f.write("};\n")
sheet.resize((8 * 95 * 2, 32), Image.NEAREST).save("/tmp/fontsheet.png")
